//! Native Shell UI crate for `clipboard`.
//!
//! Exposes [`App`], [`theme_tokens`], [`LaunchConfig`], [`configure_launch`], and [`poll_clipboard_now`].

#![forbid(unsafe_code)]

mod overlay;
mod pages;
mod shell;
mod state;
mod ui;

use nsh_base::theme;
use nsh_core::prelude::IntoElement;
use nsh_core::prelude::ParentElement;
use nsh_core::prelude::Styled;
use nsh_core::prelude::component;
use nsh_core::prelude::view;

pub use state::LaunchConfig;
pub use state::PlatformFactory;
pub use state::configure_launch;
pub use state::poll_clipboard_now;
pub use ui::tokens::theme_tokens;

/// Root Native Shell component for `clipboard`.
#[component]
#[expect(
    clippy::exhaustive_structs,
    reason = "generated by nsh_macros::component"
)]
pub fn App() -> impl IntoElement {
    state::ensure_started();

    view()
        .flex_1()
        .bg(move || theme().background)
        .text_color(move || theme().foreground)
        .child(shell::shell())
}

/// Standalone Quick Paste Overlay component (used for direct headless UI testing of the overlay).
#[component]
#[expect(
    clippy::exhaustive_structs,
    reason = "generated by nsh_macros::component"
)]
pub fn OverlayHarness() -> impl IntoElement {
    state::ensure_started();
    state::open_overlay();

    view()
        .flex_1()
        .items_center()
        .justify_center()
        .bg(move || theme().background)
        .child(overlay::overlay_surface())
}
